function tipFor(title: string, category: string) {
  if (title.includes("AI")) return "可以使用你平时习惯的AI工具，回序不会自动上传内容或调用AI。";
  if (title.includes("中草药") || title.includes("药材")) return "只了解文化与常识信息，不把内容作为服用、剂量或医疗建议。";
  if (category === "nature") return "选择安全、公开、容易到达的环境，只使用自然掉落且确认安全的素材。";
  if (title.includes("拼贴画")) return "可以把几张照片、文字和色块组合成一张新的图片。";
  if (title.includes("小故事") || title.includes("小诗") || title.includes("随笔")) return "不需要写得完整或漂亮，想到什么就写什么。";
  if (title.includes("朋友") || title.includes("家人") || title.includes("一个人")) return "选择让自己感到安全、舒服的对象和方式，不需要勉强社交。";
  return undefined;
}

export const lifeSparkCategories = categorySeeds.map(({ category, categoryName }) => ({ category, categoryName }));

export const lifeSparkItems: LifeSparkItem[] = categorySeeds.flatMap(({ category, categoryName, items }) =>
  items.map((title, index) => ({
    id: `${category}_${String(index + 1).padStart(3, "0")}`,
    category,
    categoryName,
    title,
    tip: tipFor(title, category),
  })),
);

export function drawLifeSpark(data: LifeSparkData, random = Math.random) {
  const recent = new Set([data.lastDrawnItemId, ...data.recentDraws].filter(Boolean));
  const freshPool = lifeSparkItems.filter((item) => !recent.has(item.id));
  const pool = freshPool.length ? freshPool : lifeSparkItems.filter((item) => item.id !== data.lastDrawnItemId);
  const safePool = pool.length ? pool : lifeSparkItems;
  return safePool[Math.floor(random() * safePool.length)];
}

